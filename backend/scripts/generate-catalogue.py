"""Generate matching Flyway catalogue migrations from the supplied UTF-8 archive."""

import csv
import io
from pathlib import Path
import zipfile

root = Path(__file__).resolve().parents[2]
with zipfile.ZipFile(root / "article/typing-course-txt.zip") as archive:
    index = list(
        csv.DictReader(
            io.StringIO(archive.read("course-index.csv").decode("utf-8-sig"))
        )
    )
    assert len(index) == 120
    courses = [
        ("倉頡", 10),
        ("嘸蝦米", 11),
        ("注音", 12),
        ("英文", 13),
        ("中文長文", 14),
        ("英文長文", 15),
    ]
    records = []
    levels = {"初級": "beginner", "中級": "intermediate", "高級": "advanced"}
    for row in index:
        category = row["輸入法"] if row["語言"] == "中文" else "英文"
        cid = dict(courses)[category]
        records.append(
            (
                cid,
                f"{row['課程ID']} · {row['主題']}（{row['等級']}）",
                archive.read(row["TXT路徑"]).decode("utf-8"),
                levels[row["等級"]],
            )
        )
    for name in sorted(archive.namelist()):
        if not name.startswith("txt/長文/") or not name.endswith(".txt"):
            continue
        cid = 14 if "/中文/" in name else 15
        code = Path(name).stem
        label = "全文" if "-P" not in code else f"第{code.rsplit('-P', 1)[1]}段"
        records.append(
            (cid, f"{code} · {label}", archive.read(name).decode("utf-8"), "advanced")
        )
    assert len(records) == 200
    assert all(content and len(content) < 20000 for _, _, content, _ in records)
    assert len({title for _, title, _, _ in records}) == 200

for dialect in ["migration", "sqlserver"]:

    def quote(value):
        return (
            ("N" if dialect == "sqlserver" else "")
            + "'"
            + value.replace("'", "''")
            + "'"
        )

    separator = "GO\n" if dialect == "sqlserver" else ""
    schema = (
        "ALTER TABLE articles ADD archived INTEGER NOT NULL DEFAULT 0;\n"
        + separator
        + "ALTER TABLE articles ADD CONSTRAINT articles_archived CHECK (archived IN (0,1));\n"
    )
    target = root / "backend/src/main/resources/db" / dialect
    (target / "V5__article_archive.sql").write_text(schema, encoding="utf-8")
    lines = [
        "-- Generated by backend/scripts/generate-catalogue.py; preserve archived article IDs for history.",
        "UPDATE articles SET archived=1;",
        "INSERT INTO courses (id,title,description) VALUES",
    ]
    lines.append(
        ",\n".join(
            f"({cid},{quote(title)},{quote('生成教材：' + title + '抄打練習。')})"
            for title, cid in courses
        )
        + ";"
    )
    lines.append(
        "INSERT INTO articles (id,course_id,title,content,members_only,difficulty,archived) VALUES"
    )
    lines.append(
        ",\n".join(
            f"({1001+i},{cid},{quote(title)},{quote(content)},{'0' if dialect == 'sqlserver' else 'FALSE'},{quote(level)},0)"
            for i, (cid, title, content, level) in enumerate(records)
        )
        + ";"
    )
    (target / "V6__generated_catalogue.sql").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
print(
    "Validated and generated 200 articles across 6 courses for PostgreSQL and SQL Server."
)
