CREATE TABLE members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 birthday DATE NOT NULL,
 phone VARCHAR(30) NOT NULL,
 name VARCHAR(80) NOT NULL,
 nickname VARCHAR(80) NOT NULL
);
CREATE TABLE courses (id BIGINT PRIMARY KEY, title VARCHAR(100) NOT NULL, description VARCHAR(500) NOT NULL);
CREATE TABLE articles (
 id BIGINT PRIMARY KEY, course_id BIGINT NOT NULL REFERENCES courses(id),
 title VARCHAR(100) NOT NULL, content TEXT NOT NULL, members_only BOOLEAN NOT NULL
);
CREATE TABLE attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 member_id BIGINT NOT NULL REFERENCES members(id), article_id BIGINT NOT NULL REFERENCES articles(id),
 content_snapshot TEXT NOT NULL, started_at TIMESTAMP WITH TIME ZONE NOT NULL,
 finished_at TIMESTAMP WITH TIME ZONE, elapsed_ms BIGINT, typed_text TEXT,
 correct_chars INTEGER, cpm DOUBLE PRECISION, wpm DOUBLE PRECISION, accuracy DOUBLE PRECISION,
 status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS'
);
CREATE INDEX attempts_member_started ON attempts(member_id, started_at DESC);
